class BaseHasCacheKey:
    __slots__ = ()

    @cython.boundscheck(False)
    @cython.wraparound(False)
    def _gen_cache_key(
        self, am: anon_map, bindparams: List[BindParameter[Any]]
    ) -> Optional[Tuple[Any, ...]]:
        """return an optional cache key.

        The cache key is a tuple which can contain any series of
        objects that are hashable and also identifies
        this object uniquely within the presence of a larger SQL expression
        or statement, for the purposes of caching the resulting query.

        The cache key should be based on the SQL compiled structure that would
        ultimately be produced.   That is, two structures that are composed in
        exactly the same way should produce the same cache key; any difference
        in the structures that would affect the SQL string or the type handlers
        should result in a different cache key.

        If a structure cannot produce a useful cache key, the NO_CACHE
        symbol should be added to the anon_map and the method should
        return None.

        """
        cls = self.__class__

        id_: object

        if cython.compiled:
            # inline of anon_map.get_anon(), which otherwise costs a Python
            # level call plus a throwaway (id, found) tuple per node
            am_dict = cython.cast(dict, am)
            idself: object = id(self)
            if idself in am_dict:
                return (am_dict[idself], cls)
            id_ = am._add_missing(idself)
        else:
            id_, found = am.get_anon(self)
            if found:
                return (id_, cls)

        try:
            dispatcher = cls.__dict__["_generated_cache_key_traversal"]
        except KeyError:
            # traversals.py -> _preconfigure_traversals()
            # may be used to run these ahead of time, but
            # is not enabled right now.
            # this block will generate any remaining dispatchers.
            dispatcher = cls._generate_cache_attrs()  # type: ignore[attr-defined]  # noqa: E501

        if dispatcher is _NO_CACHE:
            am[_NO_CACHE] = True
            return None

        disp_cls: ClassAttrs = dispatcher
        result: list[Any] = [id_, cls]
        elements: tuple[Any, ...] = disp_cls.elements
        element: AttrInfo
        py_method: AttrInfoMethod

        for element in elements:
            obj = getattr(self, element.name)
            kind: cython.int = element.kind
            if obj is not None:
                if kind == _STATIC_CACHE_KEY:
                    sck = obj._static_cache_key
                    if sck is _NO_CACHE:
                        am[_NO_CACHE] = True
                        return None
                    result.append(element.name)
                    result.append(sck)
                elif kind == _ANON_NAME:
                    if isinstance(obj, disp_cls.anon_label):
                        obj = obj.apply_map(am)  # type: ignore[attr-defined]
                    result.append(element.name)
                    result.append(obj)
                elif kind == _CALL_GEN_CACHE_KEY:
                    result.append(element.name)
                    result.append(obj._gen_cache_key(am, bindparams))

                # remaining cache functions are against
                # Python tuples, dicts, lists, etc. so we can skip
                # if they are empty
                elif obj:
                    if kind == _CACHE_IN_PLACE:
                        result.append(element.name)
                        result.append(obj)
                    elif kind == _PROPAGATE_ATTRS:
                        result.append(element.name)
                        result.append(obj["compile_state_plugin"])
                        if ps := obj["plugin_subject"]:
                            result.append(ps._gen_cache_key(am, bindparams))
                        else:
                            result.append(None)

                    elif kind == _ANNOTATIONS_KEY:
                        # obj is here is the _annotations dict.  Table uses
                        # a memoized version of it.  however in other cases,
                        # we generate it given am as we may be from a
                        # Join, Aliased, etc.
                        # see #8790

                        if self._gen_static_annotations_cache_key:  # type: ignore[attr-defined]  # noqa: E501
                            result.extend(self._annotations_cache_key)  # type: ignore[attr-defined]  # noqa: E501
                        else:
                            result.extend(self._gen_annotations_cache_key(am))  # type: ignore[attr-defined]  # noqa: E501

                    elif kind == _CLAUSEELEMENT_LIST:
                        result.append(element.name)
                        result.append(
                            tuple(
                                [
                                    elem._gen_cache_key(am, bindparams)
                                    for elem in obj
                                ]
                            ),
                        )
                    elif kind == _PY_METHOD:
                        py_method = element  # type: ignore[assignment]
                        result.extend(
                            py_method.meth(  # type: ignore[operator]
                                py_method.name, obj, self, am, bindparams
                            )
                        )
                    else:
                        raise NotImplementedError(f"Unknown kind {kind}")

        return tuple(result)


class CacheConst(Enum):
    NO_CACHE = 0
    PARAMS = 1


