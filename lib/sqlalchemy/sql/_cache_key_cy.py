"""Cython implementation of the cache key traversal.

The traversal for a single class is represented as a :class:`.ClassAttrs`
holding one :class:`.AttrInfo` per attribute that participates in the cache
key.  :class:`.AttrInfo` records the attribute name together with an integer
``kind`` identifying its handler, so that when compiled the per-attribute
dispatch in :meth:`.BaseHasCacheKey._gen_cache_key` is a comparison against a
C integer, rather than the chain of Python ``is`` comparisons against
singleton handler objects that the pure Python traversal loop has to run per
attribute, per cache key.

Traversal kinds that have no inline handler are represented by
:class:`.AttrInfoMethod`, which additionally carries the Python level visit
function to call; these are dispatched under the ``_PY_METHOD`` kind.

Recursion into child elements calls ``_gen_cache_key()`` on the child, which
is this compiled method for the classes that inherit it and the Python level
override otherwise.

"""

