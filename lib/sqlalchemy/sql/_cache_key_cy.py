class CacheTraverseTarget(Enum):
    """Handlers that the traversal implements inline.

    The value of each member is the integer ``kind`` recorded on the
    :class:`.AttrInfo` for an attribute using that handler, so that the
    traversal can switch on a C integer.

    """

    CACHE_IN_PLACE = _CACHE_IN_PLACE
    CALL_GEN_CACHE_KEY = _CALL_GEN_CACHE_KEY
    STATIC_CACHE_KEY = _STATIC_CACHE_KEY
    PROPAGATE_ATTRS = _PROPAGATE_ATTRS
    ANON_NAME = _ANON_NAME


# the traversal kind for each handler that _generate_class_attrs() may find.
# CacheTraverseTarget members carry their own kind as the enum value; the
# InternalTraversal symbols below have an inline handler but no dedicated
# CacheTraverseTarget member.
_attr_info_kind: Dict[Any, int] = {
    **{member: member.value for member in CacheTraverseTarget},
    InternalTraversal.dp_annotations_key: _ANNOTATIONS_KEY,
    InternalTraversal.dp_clauseelement_list: _CLAUSEELEMENT_LIST,
    InternalTraversal.dp_clauseelement_tuple: _CLAUSEELEMENT_LIST,
    InternalTraversal.dp_memoized_select_entities: _CLAUSEELEMENT_LIST,
}


@cython.cclass
class AttrInfo:
    """An attribute of a specific kind"""

    kind: cython.int
    name: str

    def __init__(self, kind: cython.int, name: str) -> None:
        self.kind = kind
        self.name = name


@cython.cclass
class AttrInfoMethod(AttrInfo):
    """An attribute that requires a python method."""

    meth: object

    def __init__(self, name: str, arg: object) -> None:
        self.kind = _PY_METHOD
        self.name = name
        self.meth = arg


@cython.cclass
class ClassAttrs:
    """The whole cache key traversal for a single class."""

    elements: tuple[AttrInfo, ...]
    anon_label: type

    def __init__(self, elements: Sequence[AttrInfo], anon_label: type) -> None:
        self.elements = tuple(elements)
        self.anon_label = anon_label


class _BaseCacheKeyTraversal:
    """Builds the per-class traversal structure that
    :meth:`.BaseHasCacheKey._gen_cache_key` consumes.

    Mixed in alongside :class:`.HasTraversalDispatch`, which supplies
    :meth:`.dispatch`; the visit symbols themselves are declared by
    :class:`._CacheKeyTraversal` in ``sql/cache_key.py``.

    """

    __slots__ = ()

    if TYPE_CHECKING:

        def dispatch(
            self, visit_symbol: InternalTraversal
        ) -> Callable[..., Any]: ...

    def generate_class_attrs(
        self,
        # NOTE: not annotated as "type": cython enforces annotations on a
        # compiled function and rejects subclasses of builtin types, which
        # fails for any class using a metaclass, e.g. _MetaOptions
        target_cls: Any,
        internal_dispatch: _TraverseInternalsType,
        attrname: str,
    ) -> ClassAttrs:
        """Build the :class:`.ClassAttrs` for ``target_cls`` and memoize it
        on the class under ``attrname``.

        """
        class_attrs = self._generate_class_attrs(internal_dispatch)
        setattr(target_cls, attrname, class_attrs)
        return class_attrs

    @util.preload_module("sqlalchemy.sql.elements")
    def _generate_class_attrs(
        self, internal_dispatch: _TraverseInternalsType
    ) -> ClassAttrs:
        """Resolve the handler for every attribute that participates in the
        cache key for a single class.

        In contrast to :meth:`.HasTraversalDispatch._generate_dispatcher`,
        which emits a function returning a list of
        ``(attrname, value, handler)`` triples that a runtime loop then has to
        interpret, this returns a :class:`.ClassAttrs` holding one
        :class:`.AttrInfo` per attribute, with the handler recorded as an
        integer kind.   Which handler applies to which attribute is a fact
        that's constant for the class, so it's resolved once here rather than
        being rediscovered by a chain of ``is`` comparisons on every cache key
        generation.

        Attributes whose handler has no inline form in the traversal are
        recorded as :class:`.AttrInfoMethod`, which carries the visit method
        itself.

        """
        elems: List[AttrInfo] = []
        meth: Any

        for attrname, visit_sym in internal_dispatch:
            meth = self.dispatch(visit_sym)
            if meth is None:
                continue

            if meth in _attr_info_kind:
                elems.append(AttrInfo(_attr_info_kind[meth], attrname))
            elif isinstance(meth, (CacheTraverseTarget, InternalTraversal)):
                raise NotImplementedError(
                    "No cache key traversal generation rule for symbol "
                    f"{meth!r}, used by attribute {attrname!r}"
                )
            else:
                elems.append(AttrInfoMethod(attrname, meth))

        return ClassAttrs(elems, util.preloaded.sql_elements._anonymous_label)
